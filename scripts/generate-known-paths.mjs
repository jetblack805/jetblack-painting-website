import fs from "node:fs";
import path from "node:path";

// Emits worker/known-paths.js — the set of paths this site actually publishes.
//
// The worker uses it to decide whether an unmatched URL should return 404.
// Cloudflare's SPA fallback serves index.html with HTTP 200 for *any* path,
// which means every bad URL anyone ever links to (/au/, old Manus paths,
// typos, scraper noise) looks like a real page to Google and lands in Search
// Console as a Soft 404, burning crawl budget.
//
// Derived by scanning the generated output rather than a hand-kept list, so it
// cannot drift out of sync with the pages that exist. Run it after
// generate-static-pages.mjs.

const PUBLIC_DIR = path.resolve("public");
const OUT_PATH = path.resolve("worker/known-paths.js");

function collect(dir, prefix = "") {
  const found = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const route = `${prefix}/${entry.name}`;
    if (fs.existsSync(path.join(dir, entry.name, "index.html"))) {
      found.push(`${route}/`);
    }
    found.push(...collect(path.join(dir, entry.name), route));
  }
  return found;
}

// "/" is served by the Vite build's index.html, not from public/, so it is
// added explicitly rather than discovered.
const paths = ["/", ...collect(PUBLIC_DIR)].sort();

const file = `// GENERATED by scripts/generate-known-paths.mjs — do not edit by hand.
// Every path this site publishes, used by the worker to return a real 404
// instead of Cloudflare's SPA fallback 200 for URLs that do not exist.
export const KNOWN_PATHS = new Set(${JSON.stringify(paths, null, 2)});
`;

fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
fs.writeFileSync(OUT_PATH, file, "utf8");
console.log(`Known paths written to ${OUT_PATH} (${paths.length} paths).`);
